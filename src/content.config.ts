import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

export const CATEGORIES = [
  'Construcții eficiente',
  'Locuințe',
  'Amenajări interioare',
  'Spații comerciale',
  'Dotări pentru turism',
] as const;

const row = z.object({ k: z.string(), v: z.string() });

const projects = defineCollection({
  // Each project is a folder: src/content/projects/<slug>/index.md + its photos.
  loader: glob({ pattern: '*/index.md', base: './src/content/projects', generateId: ({ entry }) => entry.split('/')[0] }),
  schema: ({ image }) =>
    z.object({
      title: z.string(),
      location: z.string().optional(),
      year: z.string().optional(),
      categories: z.array(z.enum(CATEGORIES)).min(1),
      summary: z.string(),
      highlights: z.array(z.string()).default([]),
      // Lower numbers come first in lists. New projects get the lowest number.
      order: z.number(),
      featured: z.boolean().default(false),
      cover: image(),
      gallery: z.array(z.object({ src: image(), caption: z.string().optional() })).default([]),
      facts: z.array(row).default([]),
      technical: z.array(row).default([]),
      quote: z.object({ text: z.string(), author: z.string().optional() }).optional(),
      // True while the photos are stand-ins generated by the site, not real ones.
      placeholderPhotos: z.boolean().default(false),
      // Old WordPress address, used to build redirects.
      oldPath: z.string().optional(),
    }),
});

export const collections = { projects };
